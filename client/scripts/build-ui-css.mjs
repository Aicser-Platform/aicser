#!/usr/bin/env node
/**
 * Builds src/styles/aicser-ui.css (Aicser UI, the desktop design system on Docs and Slides) from
 * src/styles/aicser-ui.source.css with its own Tailwind config, tailwind.ui.config.ts.
 *
 * The output is kept in git and imported as plain CSS: Next never runs this second Tailwind config, which raced
 * with the main one when picked per file with `@config` (webpack compiled globals.css with the wrong config).
 *
 *   node scripts/build-ui-css.mjs           write the file
 *   node scripts/build-ui-css.mjs --check   exit 1 if it is out of date (CI, src/styles/aicser-ui.test.ts)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
import tailwindcss from 'tailwindcss';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(root, 'src/styles/aicser-ui.source.css');
const OUTPUT = path.join(root, 'src/styles/aicser-ui.css');
const CONFIG = path.join(root, 'tailwind.ui.config.ts');
const BANNER =
  '/* GENERATED by scripts/build-ui-css.mjs from aicser-ui.source.css + tailwind.ui.config.ts. Do not edit:\n' +
  '   run `npm run ui:css` after changing Aicser UI classes or tokens. */\n';

export async function buildUiCss() {
  const result = await postcss([tailwindcss({ config: CONFIG })]).process(readFileSync(SOURCE, 'utf8'), {
    from: SOURCE,
    to: OUTPUT,
  });
  return BANNER + result.css.trimEnd() + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = await buildUiCss();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUTPUT, 'utf8');
    } catch {
      // missing counts as out of date
    }
    if (current !== css) {
      console.error('src/styles/aicser-ui.css is out of date: run `npm run ui:css`.');
      process.exit(1);
    }
    console.log('src/styles/aicser-ui.css is up to date.');
  } else {
    writeFileSync(OUTPUT, css);
    console.log('Wrote src/styles/aicser-ui.css');
  }
}
